SIZES = {group: value.bit_length() // 8 for group, value in PRIMES.items()}


@lru_cache(maxsize=5)
def parameters(group):
    if group not in PRIMES:
        raise ProtocolError("unknown finite-field group", alert=47)
    prime = PRIMES[group]
    return DHParameterNumbers(prime, 2, (prime - 1) // 2).parameters()


def generate(group):
    private = parameters(group).generate_private_key()
    return private, private.public_key().public_numbers().y.to_bytes(SIZES[group], "big")


def _quadratic_residue(value, prime):
    """Legendre symbol via binary Jacobi, for the fixed public prime moduli.

    Since every modulus here is an RFC 7919 prime, a Jacobi symbol of one is
    exactly membership in its order-q subgroup. This avoids an expensive
    public modular exponentiation on the event loop. Neither argument nor any
    intermediate contains a private exponent; secret DH stays in the provider.
    """
    sign = 1
    while value:
        twos = (value & -value).bit_length() - 1
        value >>= twos
        if twos & 1 and prime & 7 in (3, 5):
            sign = -sign
        if value & 3 == prime & 3 == 3:
            sign = -sign
        value, prime = prime % value, value
    return prime == 1 and sign == 1


def exchange(private, group, encoded):
    if not isinstance(private, DHPrivateKey) or len(encoded) != SIZES[group]:
        raise ProtocolError("invalid finite-field key share", alert=47)
    prime = PRIMES[group]
    value = int.from_bytes(encoded, "big")
    if not 1 < value < prime - 1 or private.parameters().parameter_numbers().p != prime:
        raise ProtocolError("invalid finite-field share bounds", alert=47)
    # Only public values participate in this membership check. The provider's
    # exchange API does not consistently expose its optional subgroup check.
    if not _quadratic_residue(value, prime):
        raise ProtocolError("invalid finite-field subgroup", alert=47)
    try:
        # Every operation involving the private exponent remains in OpenSSL.
        public = DHPublicNumbers(value, parameters(group).parameter_numbers()).public_key()
        return private.exchange(public).rjust(SIZES[group], b"\x00")
    except ValueError as error:
        raise ProtocolError("invalid finite-field subgroup or shared secret", alert=47) from error
